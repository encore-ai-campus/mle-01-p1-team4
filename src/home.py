# =========================================================
# PDF 원문
# =========================================================


def get_regulation_pdfs():
    """
    data/raw 폴더에 존재하는 PDF 파일의
    문서명과 경로를 반환합니다.
    """

    pdfs = []

    # data/raw 폴더가 없으면 빈 리스트 반환
    if not RAW_PDF_DIR.exists():
        return pdfs

    for pdf_path in sorted(
        RAW_PDF_DIR.glob("*.pdf")
    ):
        pdfs.append(
            {
                "document_name": pdf_path.stem,
                "path": pdf_path,
            }
        )

    return pdfs

